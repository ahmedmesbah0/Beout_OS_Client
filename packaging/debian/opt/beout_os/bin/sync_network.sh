#!/bin/bash
# Synchronizes SQLite configuration to the Debian OS network interfaces
set -e

DB_PATH="/var/lib/beout_os/config.db"
INTERFACES_FILE="/etc/network/interfaces.d/beout_os_interfaces"
LOG_FILE="/var/log/beout_os_network_sync.log"

mkdir -p "$(dirname "$LOG_FILE")"
touch "$LOG_FILE" 2>/dev/null || true
exec >> "$LOG_FILE" 2>&1

log() {
    printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*"
}

run_cmd() {
    log "CMD: $*"
    "$@"
    local status=$?
    if [ "$status" -ne 0 ]; then
        log "WARN: command failed status=${status}: $*"
    fi
    return "$status"
}

log "=== Beout_OS network sync started ==="
log "DB_PATH=${DB_PATH} INTERFACES_FILE=${INTERFACES_FILE}"
log "Detected adapters: $(ls /sys/class/net 2>/dev/null | tr '\n' ' ')"

# Reset /etc/network/interfaces to a clean, minimal state to prevent service start failures
cat <<EOF > /etc/network/interfaces
# This file describes the network interfaces available on your system
# and how to activate them. For more information, see interfaces(5).

source /etc/network/interfaces.d/*

# The loopback network interface
auto lo
iface lo inet loopback
EOF

# Helper to convert netmask to CIDR prefix
mask2cidr() {
    case "$1" in
        255.255.255.255) echo 32 ;;
        255.255.255.254) echo 31 ;;
        255.255.255.252) echo 30 ;;
        255.255.255.248) echo 29 ;;
        255.255.255.240) echo 28 ;;
        255.255.255.224) echo 27 ;;
        255.255.255.192) echo 26 ;;
        255.255.255.128) echo 25 ;;
        255.255.255.0)   echo 24 ;;
        255.255.254.0)   echo 23 ;;
        255.255.252.0)   echo 22 ;;
        255.255.248.0)   echo 21 ;;
        255.255.240.0)   echo 20 ;;
        255.255.224.0)   echo 19 ;;
        255.255.192.0)   echo 18 ;;
        255.255.128.0)   echo 17 ;;
        255.255.0.0)     echo 16 ;;
        255.254.0.0)     echo 15 ;;
        255.252.0.0)     echo 14 ;;
        255.248.0.0)     echo 13 ;;
        255.240.0.0)     echo 12 ;;
        255.224.0.0)     echo 11 ;;
        255.192.0.0)     echo 10 ;;
        255.128.0.0)     echo 9 ;;
        255.0.0.0)       echo 8 ;;
        254.0.0.0)       echo 7 ;;
        252.0.0.0)       echo 6 ;;
        248.0.0.0)       echo 5 ;;
        240.0.0.0)       echo 4 ;;
        224.0.0.0)       echo 3 ;;
        192.0.0.0)       echo 2 ;;
        128.0.0.0)       echo 1 ;;
        0.0.0.0)         echo 0 ;;
        *)               echo 24 ;; # Default fallback
    esac
}

# Helper to apply the configuration immediately to the live system
apply_interface_live() {
    local dev="$1"
    local ip="$2"
    local netmask="$3"
    local gateway="$4"
    local metric="$5"

    if [ -n "$dev" ] && [ -n "$ip" ]; then
        # Check if device exists in system
        if ip link show "$dev" >/dev/null 2>&1; then
            log "Applying ip=${ip} netmask=${netmask:-none} gateway=${gateway:-none} metric=${metric:-none} dev=${dev}"
            
            # Determine prefix length
            local prefix=24
            if [ -n "$netmask" ]; then
                prefix=$(mask2cidr "$netmask")
            fi
            
            # Flush existing IP addresses to avoid conflicts
            run_cmd ip addr flush dev "$dev" || true
            
            # Add new IP address
            run_cmd ip addr add "$ip/$prefix" dev "$dev" || true
            
            # Bring link up
            run_cmd ip link set "$dev" up || true
            
            # Apply gateway if specified
            if [ -n "$gateway" ]; then
                # Delete existing default route on this device
                run_cmd ip route del default dev "$dev" || true
                
                # Add route with metric
                if [ -n "$metric" ]; then
                    run_cmd ip route add default via "$gateway" dev "$dev" metric "$metric" || true
                else
                    run_cmd ip route add default via "$gateway" dev "$dev" || true
                fi
            fi
        else
            log "WARN: adapter device does not exist: ${dev}"
        fi
    else
        log "SKIP: missing device or IP dev=${dev:-empty} ip=${ip:-empty}"
    fi
}

# Call sqlite3 and jq helper to generate custom interfaces
INTERFACES_JSON=$(sqlite3 -cmd ".timeout 5000" "$DB_PATH" "SELECT value FROM config WHERE key='network_interfaces_json';" 2>/dev/null || echo "")
log "Loaded network_interfaces_json length=${#INTERFACES_JSON}"

if [ -n "$INTERFACES_JSON" ] && echo "$INTERFACES_JSON" | jq -e '. | type == "array"' >/dev/null 2>&1; then
    echo "# Generated by Beout_OS Configuration Engine" > "$INTERFACES_FILE"
    
    # Extract interfaces from JSON array
    echo "$INTERFACES_JSON" | jq -c '.[]' | while read -r iface; do
        ID=$(echo "$iface" | jq -r '.id // empty' | tr -d '[:space:]')
        DEVICE=$(echo "$iface" | jq -r '.device // empty' | tr -d '[:space:]')
        IP=$(echo "$iface" | jq -r '.ip // empty' | tr -d '[:space:]')
        NETMASK=$(echo "$iface" | jq -r '.netmask // empty' | tr -d '[:space:]')
        GATEWAY=$(echo "$iface" | jq -r '.gateway // empty' | tr -d '[:space:]')
        
        log "JSON iface id=${ID:-empty} device=${DEVICE:-empty} ip=${IP:-empty} netmask=${NETMASK:-empty} gateway=${GATEWAY:-empty}"
        if [ -n "$DEVICE" ] && [ -n "$IP" ]; then
            echo "auto $DEVICE" >> "$INTERFACES_FILE"
            echo "iface $DEVICE inet static" >> "$INTERFACES_FILE"
            echo "    address $IP" >> "$INTERFACES_FILE"
            if [ -n "$NETMASK" ]; then
                echo "    netmask $NETMASK" >> "$INTERFACES_FILE"
            fi
            if [ -n "$GATEWAY" ]; then
                echo "    gateway $GATEWAY" >> "$INTERFACES_FILE"
                if [ "$ID" = "wan" ]; then
                    echo "    metric 100" >> "$INTERFACES_FILE"
                elif [ "$ID" = "mgmt" ]; then
                    echo "    metric 200" >> "$INTERFACES_FILE"
                fi
            fi
            echo "" >> "$INTERFACES_FILE"

            # Apply configuration live immediately
            METRIC=""
            if [ "$ID" = "wan" ]; then
                METRIC="100"
            elif [ "$ID" = "mgmt" ]; then
                METRIC="200"
            fi
            apply_interface_live "$DEVICE" "$IP" "$NETMASK" "$GATEWAY" "$METRIC"
        fi
    done
else
    log "Using legacy network config fallback"
    # Fallback: if JSON was empty/missing, load from legacy columns
    GET_VAL() {
        sqlite3 -cmd ".timeout 5000" "$DB_PATH" "SELECT value FROM config WHERE key='$1';" 2>/dev/null || echo ""
    }

    WAN_DEV=$(GET_VAL "network_WAN_interface")
    [ -z "$WAN_DEV" ] && WAN_DEV="eth0"
    WAN_IP=$(GET_VAL "network_WAN_ip")
    WAN_NET=$(GET_VAL "network_WAN_netmask")
    [ -z "$WAN_NET" ] && WAN_NET="255.255.255.0"
    WAN_GW=$(GET_VAL "network_WAN_gateway")

    LAN_DEV=$(GET_VAL "network_LAN_interface")
    [ -z "$LAN_DEV" ] && LAN_DEV="eth1"
    LAN_IP=$(GET_VAL "network_LAN_ip")
    LAN_NET=$(GET_VAL "network_LAN_netmask")
    [ -z "$LAN_NET" ] && LAN_NET="255.255.255.0"

    MGMT_DEV=$(GET_VAL "network_MGMT_interface")
    [ -z "$MGMT_DEV" ] && MGMT_DEV="eth2"
    MGMT_IP=$(GET_VAL "network_MGMT_ip")
    MGMT_NET=$(GET_VAL "network_MGMT_netmask")
    [ -z "$MGMT_NET" ] && MGMT_NET="255.255.255.0"
    MGMT_GW=$(GET_VAL "network_MGMT_gateway")

    echo "# Generated by Beout_OS Configuration Engine" > "$INTERFACES_FILE"

    if [ -n "$WAN_IP" ]; then
        echo "auto $WAN_DEV" >> "$INTERFACES_FILE"
        echo "iface $WAN_DEV inet static" >> "$INTERFACES_FILE"
        echo "    address $WAN_IP" >> "$INTERFACES_FILE"
        echo "    netmask $WAN_NET" >> "$INTERFACES_FILE"
        if [ -n "$WAN_GW" ]; then
            echo "    gateway $WAN_GW" >> "$INTERFACES_FILE"
            echo "    metric 100" >> "$INTERFACES_FILE"
        fi
        echo "" >> "$INTERFACES_FILE"
        apply_interface_live "$WAN_DEV" "$WAN_IP" "$WAN_NET" "$WAN_GW" "100"
    fi

    if [ -n "$LAN_IP" ]; then
        echo "auto $LAN_DEV" >> "$INTERFACES_FILE"
        echo "iface $LAN_DEV inet static" >> "$INTERFACES_FILE"
        echo "    address $LAN_IP" >> "$INTERFACES_FILE"
        echo "    netmask $LAN_NET" >> "$INTERFACES_FILE"
        echo "" >> "$INTERFACES_FILE"
        apply_interface_live "$LAN_DEV" "$LAN_IP" "$LAN_NET" "" ""
    fi

    if [ -n "$MGMT_IP" ]; then
        echo "auto $MGMT_DEV" >> "$INTERFACES_FILE"
        echo "iface $MGMT_DEV inet static" >> "$INTERFACES_FILE"
        echo "    address $MGMT_IP" >> "$INTERFACES_FILE"
        echo "    netmask $MGMT_NET" >> "$INTERFACES_FILE"
        if [ -n "$MGMT_GW" ]; then
            echo "    gateway $MGMT_GW" >> "$INTERFACES_FILE"
            echo "    metric 200" >> "$INTERFACES_FILE"
        fi
        echo "" >> "$INTERFACES_FILE"
        apply_interface_live "$MGMT_DEV" "$MGMT_IP" "$MGMT_NET" "$MGMT_GW" "200"
    fi
fi

# Reload networking to apply changes
log "Generated interfaces file:"
sed 's/^/[interfaces] /' "$INTERFACES_FILE" 2>/dev/null || true
log "Kernel addresses before networking restart:"
ip -br addr show 2>/dev/null || true
systemctl restart networking || log "WARN: systemctl restart networking failed"
log "Kernel addresses after networking restart:"
ip -br addr show 2>/dev/null || true
log "Routes after networking restart:"
ip route show table all 2>/dev/null || true
log "=== Beout_OS network sync finished ==="
