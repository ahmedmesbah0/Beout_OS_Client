#!/bin/bash
# Synchronizes SQLite configuration to the Debian OS network interfaces
set -e

DB_PATH="/var/lib/beout_os/config.db"
INTERFACES_FILE="/etc/network/interfaces.d/beout_os_interfaces"

# Reset /etc/network/interfaces to a clean, minimal state to prevent service start failures
cat <<EOF > /etc/network/interfaces
# This file describes the network interfaces available on your system
# and how to activate them. For more information, see interfaces(5).

source /etc/network/interfaces.d/*

# The loopback network interface
auto lo
iface lo inet loopback
EOF

# Call Python helper to generate custom interfaces
python3 -c "
import sqlite3
import json

db_path = '$DB_PATH'
out_path = '$INTERFACES_FILE'

try:
    conn = sqlite3.connect(db_path)
    c = conn.cursor()
    c.execute(\"SELECT value FROM config WHERE key='network_interfaces_json'\")
    r = c.fetchone()
    if r:
        interfaces = json.loads(r[0])
    else:
        interfaces = []
except Exception as e:
    print(f'Error reading database: {e}')
    interfaces = []

# Fallback: if JSON was empty/missing, load from legacy columns
if not interfaces:
    try:
        c.execute(\"SELECT key, value FROM config WHERE key LIKE 'network_%'\")
        rows = c.fetchall()
        kvs = {row[0]: row[1] for row in rows}
        
        wan_dev = kvs.get('network_WAN_interface', 'eth0')
        wan_ip = kvs.get('network_WAN_ip', '')
        wan_net = kvs.get('network_WAN_netmask', '255.255.255.0')
        wan_gw = kvs.get('network_WAN_gateway', '')
        
        lan_dev = kvs.get('network_LAN_interface', 'eth1')
        lan_ip = kvs.get('network_LAN_ip', '')
        lan_net = kvs.get('network_LAN_netmask', '255.255.255.0')
        
        mgmt_dev = kvs.get('network_MGMT_interface', 'eth2')
        mgmt_ip = kvs.get('network_MGMT_ip', '')
        mgmt_net = kvs.get('network_MGMT_netmask', '255.255.255.0')
        mgmt_gw = kvs.get('network_MGMT_gateway', '')
        
        interfaces = [
            {'device': wan_dev, 'ip': wan_ip, 'netmask': wan_net, 'gateway': wan_gw},
            {'device': lan_dev, 'ip': lan_ip, 'netmask': lan_net, 'gateway': ''},
            {'device': mgmt_dev, 'ip': mgmt_ip, 'netmask': mgmt_net, 'gateway': mgmt_gw}
        ]
    except Exception as e:
        print(f'Error reading legacy database keys: {e}')

with open(out_path, 'w') as f:
    f.write('# Generated by Beout_OS Configuration Engine\n\n')
    for iface in interfaces:
        device = iface.get('device', '').strip()
        ip = iface.get('ip', '').strip()
        netmask = iface.get('netmask', '').strip()
        gateway = iface.get('gateway', '').strip()
        
        if device and ip:
            f.write(f'auto {device}\n')
            f.write(f'iface {device} inet static\n')
            f.write(f'    address {ip}\n')
            if netmask:
                f.write(f'    netmask {netmask}\n')
            if gateway:
                f.write(f'    gateway {gateway}\n')
            f.write('\n')
"

# Reload networking to apply changes
systemctl restart networking || true
